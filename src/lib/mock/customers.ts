export interface Customer {
  id: string;
  companyName: string;
  businessRegNo: string;
  services: string[];
  contactPerson: string;
  createdAt: string;
  createdAtTimestamp?: number; // Timestamp for "New" badge
  resellerId?: string; // null/undefined means direct WM customer
  companyId?: string; // Customer's company ID
  country?: string;
  ceo?: string;
  email?: string;
}

export interface CustomerNote {
  id: string;
  customerId: string;
  content: string;
  author: string;
  createdAt: string;
}

export interface CustomerContract {
  id: string;
  customerId: string;
  serviceName: string;
  pricingModel: 'Fixed Rate' | 'Pay-as-you-go';
  startDate: string;
  endDate: string;
  amount: string;
  status: 'active' | 'inactive' | 'expired' | 'pending' | 'rejected';
  details: string;
}

export interface PaymentHistory {
  id: string;
  customerId: string;
  invoiceNo: string;
  period: string;
  date: string;
  service: string;
  status: 'paid' | 'unpaid' | 'overdue';
  paidAmount: string;
  difference: string;
}

