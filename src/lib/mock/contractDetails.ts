import { Contract } from './contracts';

// Extended contract detail interface
export interface ContractDetail extends Contract {
  contractId?: string; // Display ID like "CO11"
  customerId?: string;
  contactPerson?: {
    name: string;
    email: string;
  };
  createdAt?: string;
  billingInfo?: BillingInfoFixedRate | BillingInfoPayAsYouGo | BillingInfoTrial;
  billingEmails?: string[];
  vcpuUsage?: VCPUUsageData[]; // Only for Fixed Rate
  usageCostData?: UsageCostData[]; // Only for Pay-as-you-go
  notes?: ContractNote[];
  paymentHistory?: PaymentHistory[];
  approvalStatus?: 'pending' | 'approved' | 'rejected';
  submittedDate?: string;
  rejectionReason?: string;
}

// Billing info for Fixed Rate pricing model
export interface BillingInfoFixedRate {
  type: 'Fixed Rate';
  includedAllocation: number; // vCPU limit
  contractPeriod: string;
  contractAmount: string;
  taxIncluded: boolean;
}

// Billing info for Pay-as-you-go pricing model
export interface BillingInfoPayAsYouGo {
  type: 'Pay-as-you-go';
  rate: string; // e.g., "$30 / hour"
  contractPeriod: string;
  minimumCharge: string;
  taxIncluded: boolean;
}

// Billing info for Trial pricing model
export interface BillingInfoTrial {
  type: 'Trial';
  trialAllocation: number; // vCPU limit for trial
  trialPeriod: string;
  note?: string; // Optional note about trial terms
}

// vCPU usage data for charts (Fixed Rate only)
export interface VCPUUsageData {
  month: string;
  used: number;
  limit: number;
}

// Usage cost data for charts (Pay-as-you-go only)
export interface UsageCostData {
  month: string;
  cost: number;
  minimumCharge: number;
}

// Contract notes
export interface ContractNote {
  id: string;
  content: string;
  createdAt: string;
  createdBy: string;
}

// Payment history
export interface PaymentHistory {
  id: string;
  invoiceNo: string;
  period: string;
  date: string;
  status: 'Paid' | 'Pending' | 'Partial';
  paidAmount: string;
  difference: string;
}

